const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
test('React Native Mine is a personal content screen rather than developer settings',()=>{
 const page=read('apps/mobile/src/screens/MineScreen.tsx')
 const app=read('apps/mobile/App.tsx')
 for(const key of ['我的收藏','我的配方','我的分享','数据同步','设置与隐私','AsyncStorage.setItem(PROFILE_KEY'])
   assert.ok(page.includes(key),key)
 for(const key of ['设备令牌','API_BASE_URL','ENABLE_DEVICE_TOKEN_TESTING','saveMobileTestToken','deviceToken'])
   assert.ok(!page.includes(key),key)
 assert.ok(app.includes('<MineScreen'))
 assert.ok(app.includes('toggleFavorite('))
 assert.ok(app.includes('FAVORITES_KEY'))
 assert.ok(!app.includes('saveMobileTestToken'))
})
